"""Generate responsive WebP assets and their TypeScript metadata.

Requires Pillow: python3 -m pip install Pillow
Run from the project root: python3 scripts/convert-images.py
Original PNG files remain available as editable sources.
"""
from pathlib import Path
import json
import re
from PIL import Image, ImageOps

root = Path(__file__).resolve().parent.parent
sources = set()
for module in (root / 'src').rglob('*.ts*'):
    if module.name == 'image-manifest.ts':
        continue
    for reference in re.findall(r'''["']([^"']+\.(?:png|webp))["']''', module.read_text()):
        if reference.startswith('/assets/'):
            source = root / 'public' / reference.lstrip('/')
        elif reference.startswith('../'):
            source = module.parent / reference
        else:
            continue
        source = source.with_suffix('.png').resolve()
        if source.exists():
            sources.add(source)

imports, entries = [], []
def image_url(path, name):
    if path.is_relative_to(root / 'public'):
        return json.dumps('/' + str(path.relative_to(root / 'public')))
    imports.append(f'import {name} from {json.dumps("../../" + str(path.relative_to(root)))};')
    return name

before = after = 0
for index, source in enumerate(sorted(sources)):
    target = source.with_suffix('.webp')
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original)
        image = image.convert('RGBA' if 'A' in image.getbands() or 'transparency' in image.info else 'RGB')
        image.save(target, 'WEBP', quality=88, method=6)
        with Image.open(target) as converted:
            assert converted.size == image.size
            if image.mode == 'RGBA':
                assert converted.convert('RGBA').getchannel('A').tobytes() == image.getchannel('A').tobytes()
        full_url = image_url(target, f'image{index}')
        candidates = []
        for width in [320, 640, 960, 1280, 1600]:
            if width >= image.width:
                continue
            height = max(1, round(image.height * width / image.width))
            variant = target.with_stem(f'{target.stem}-{width}')
            image.resize((width, height), Image.Resampling.LANCZOS).save(variant, 'WEBP', quality=88, method=6)
            candidates.append(f'{{ src: {image_url(variant, f"image{index}_{width}")}, width: {width} }}')
        candidates.append(f'{{ src: {full_url}, width: {image.width} }}')
        entries.append(f'  [{full_url}]: {{ width: {image.width}, height: {image.height}, candidates: [{", ".join(candidates)}] }},')
    old, new = source.stat().st_size, target.stat().st_size
    before += old
    after += new
    print(f'{source.relative_to(root)}: {old / 1024:.0f} → {new / 1024:.0f} KB')
manifest = '// Generated by scripts/convert-images.py; do not edit by hand.\n' + '\n'.join(imports)
manifest += '\n\nexport const IMAGE_MANIFEST: Record<string, { width: number; height: number; candidates: { src: string; width: number }[] }> = {\n'
manifest += '\n'.join(entries) + '\n};\n'
(root / 'src/data/image-manifest.ts').write_text(manifest)
print(f'{len(sources)} images: {before:,} → {after:,} bytes ({(1 - after / before) * 100:.1f}% smaller at full resolution)')
